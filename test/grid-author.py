"""真实地球栅格的**生成工具**（`data/earth1945.js` 里那张字符画就是它吐出来的）

用法：
    python3 test/grid-author.py            # 打印栅格 + 每国的格数与包围盒
    python3 test/grid-author.py emit       # 打印可以直接粘回 data/earth1945.js 的 grid 块

为什么它不在 js/ 里：游戏本身一行 Python 都不需要（零依赖是底线）。
这个文件是**开发期的脚手架** —— 但它是这套数据的真源：
`data/earth1945.js` 里的 60 行字符画是它的输出，手改那张画会在下一次 emit 时被覆盖。
要改地图，改这里的矩形，再 emit。

为什么用矩形而不是直接手画字符画：
  ① 矩形写在**经纬度**上，与分辨率无关 —— 把 COLS/ROWS 从 72×30 提到 144×60
     是一次改动，不是重画一遍（2026-09 就是这么做的，地图细节翻了四倍，工程量约等于零）
  ② 边界是**可读的**："非洲的国界来自这几条矩形"比 60 行神秘字符好维护得多
  ③ 顺序即优先级，能表达"这一块要盖在那一块上面"

分四层，顺序不能乱：
  第一层 大洲打底      —— 粗块，只需要"这块是陆地"
  第二层 国界          —— 后画的赢，边界靠顺序表达
  第三层 海            —— 在陆地上挖出来；这一层的密度是随分辨率长出来的
  第四层 海岸修正      —— 在海上盖回陆地。5° 时代画的海矩形在 2.5° 下会吞掉真实海岸
                         （海参崴就是），而把矩形改窄又会在别处把海变成陆 ——
                         5° 的粒度本来就不足以同时满足两边，所以单独留一层做点状修正。

判据不是"看起来像"：`test/scenario-test.js` 里有一份 55 个真实经纬度的抽样点清单
（每条要么必须是海、要么必须是陆），改完矩形跑一次就知道有没有把地中海填平。
"""

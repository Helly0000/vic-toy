"""世界栅格作者工具（**不随游戏发布，只是把字符画生成出来的脚手架**）。
矩形 + 单格覆盖 → 72×30 的字符画，打印出来肉眼校对。"""
import sys

COLS, ROWS = 144, 60
LAT_TOP, LAT_BOT = 84.0, -60.0
STEP = (LAT_TOP - LAT_BOT) / ROWS          # 4.8
LON0 = -180.0

grid = [['.'] * COLS for _ in range(ROWS)]

def cell(lon, lat):
    c = int((lon + 180.0) / 360.0 * COLS)
    r = int((LAT_TOP - lat) / (LAT_TOP - LAT_BOT) * ROWS)
    return r, c % COLS

def rect(code, lon0, lon1, lat0, lat1):
    """填充矩形。[lon0,lon1) × [lat0,lat1)（纬度按中心点判定）"""
    for r in range(ROWS):
        lat = LAT_TOP - (r + 0.5) * STEP
        if not (lat0 <= lat < lat1):
            continue
        for c in range(COLS):
            lon = LON0 + (c + 0.5) * (360.0 / COLS)
            if lon0 <= lon < lon1:
                grid[r][c] = code

def put(code, lon, lat):
    r, c = cell(lon, lat)
    grid[r][c] = code

R = rect   # 简写

